<?php
/**
 * Грамотні назви з каталогу (адмінки): «мотор» → «двигун», «масло» → «олива» тощо.
 * Виправляє тільки показ на сайті; самі записи в адмінці не змінює.
 */
function ep_uk_name($s) {
    if (!is_string($s) || $s === '') return $s;
    $map = [
        // мотор → двигун (але «моторна олива» не чіпаємо — правильний термін)
        'мотор' => 'двигун', 'мотора' => 'двигуна', 'мотору' => 'двигуну', 'мотором' => 'двигуном',
        'моторі' => 'двигуні', 'мотори' => 'двигуни', 'моторів' => 'двигунів', 'моторам' => 'двигунам',
        // масло → олива (технічна олива); мастило (густе) не чіпаємо
        'масло' => 'олива', 'масла' => 'оливи', 'маслу' => 'оливі', 'маслом' => 'оливою', 'маслі' => 'оливі',
        'масляний' => 'оливний', 'масляного' => 'оливного', 'масляна' => 'оливна', 'масляної' => 'оливної',
        'масляне' => 'оливне', 'масляні' => 'оливні', 'масляних' => 'оливних', 'масляному' => 'оливному',
    ];
    $s = preg_replace_callback('/(?<!\p{L})(\p{L}+)(?!\p{L})/u', function ($m) use ($map) {
        $w = $m[1];
        $low = mb_strtolower($w, 'UTF-8');
        if (!isset($map[$low])) return $w;
        $r = $map[$low];
        if ($w === mb_strtoupper($w, 'UTF-8') && mb_strlen($w, 'UTF-8') > 1) return mb_strtoupper($r, 'UTF-8');
        $first = mb_substr($w, 0, 1, 'UTF-8');
        if ($first !== mb_strtolower($first, 'UTF-8')) return mb_strtoupper(mb_substr($r, 0, 1, 'UTF-8'), 'UTF-8') . mb_substr($r, 1, null, 'UTF-8');
        return $r;
    }, $s);
    // «Датчик тиску оливи Двигуна» → «…двигуна»: велика літера всередині назви у звичайних словах
    $s = preg_replace_callback('/(?<=\s)(Двигун\p{L}*|Оливи|Оливний|Оливна|Оливного)(?!\p{L})/u', function ($m) {
        return mb_strtolower($m[1], 'UTF-8');
    }, $s);
    // узгодження: «олива гідравлічне» → «олива гідравлічна», «гідравлічне масло» → «гідравлічна олива»
    $s = preg_replace_callback('/(?<!\p{L})([Оо]лива)\s+(\p{L}+?)(не|ове)(?!\p{L})/u', function ($m) {
        return $m[1] . ' ' . $m[2] . ($m[3] === 'не' ? 'на' : 'ова');
    }, $s);
    $s = preg_replace_callback('/(?<!\p{L})(\p{L}+?)(не|ове)\s+(олива)(?!\p{L})/u', function ($m) {
        return $m[1] . ($m[2] === 'не' ? 'на' : 'ова') . ' ' . $m[3];
    }, $s);
    return $s;
}
